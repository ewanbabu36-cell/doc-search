#!/usr/bin/env node
/**
 * DocSearch Universal Gmail SMTP Setup & Verification CLI
 * ---------------------------------------------------------
 * Usage:
 *   1. Check current .env Gmail setup:
 *      node scripts/setup-gmail-smtp.mjs
 *
 *   2. Test & Save new credentials to .env:
 *      node scripts/setup-gmail-smtp.mjs your-email@gmail.com "abcd efgh ijkl mnop" --save
 *
 *   3. Test and send live email to a recipient:
 *      node scripts/setup-gmail-smtp.mjs your-email@gmail.com "abcd efgh ijkl mnop" --send-to doctor@example.com --save
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '..');
const ENV_PATH = path.join(ROOT_DIR, '.env');

const require = createRequire(path.join(ROOT_DIR, 'apps/api-gateway/package.json'));
const nodemailer = require('nodemailer');

// ANSI Colors
const BOLD = '\x1b[1m';
const GREEN = '\x1b[32m';
const RED = '\x1b[31m';
const CYAN = '\x1b[36m';
const YELLOW = '\x1b[33m';
const RESET = '\x1b[0m';

console.log(`${BOLD}${CYAN}`);
console.log('===============================================================');
console.log('       DOC SEARCH — GMAIL SMTP SETUP & VERIFICATION CLI        ');
console.log('===============================================================' + RESET);

// 1. Parse arguments or load from .env
let envContent = '';
if (fs.existsSync(ENV_PATH)) {
  envContent = fs.readFileSync(ENV_PATH, 'utf8');
}

const args = process.argv.slice(2);
let user = '';
let appPassword = '';
let sendTo = '';
let shouldSave = false;

for (let i = 0; i < args.length; i++) {
  const arg = args[i];
  if (arg === '--save') {
    shouldSave = true;
  } else if (arg === '--send-to' && args[i + 1]) {
    sendTo = args[i + 1];
    i++;
  } else if (!user && !arg.startsWith('--')) {
    user = arg;
  } else if (!appPassword && !arg.startsWith('--')) {
    appPassword = arg;
  }
}

// Fallback to .env values if not passed via CLI
if (!user) {
  const m = envContent.match(/^GMAIL_USER=(.+)$/m);
  if (m) user = m[1].trim();
}
if (!appPassword) {
  const m = envContent.match(/^GMAIL_APP_PASSWORD=(.+)$/m);
  if (m) appPassword = m[1].trim();
}

// Sanitize inputs
user = (user || '').trim();
appPassword = (appPassword || '').replace(/\s+/g, '').trim();

if (!user || !appPassword) {
  console.log(`\n${YELLOW}⚠️  Gmail SMTP Credentials Not Found in .env or CLI arguments!${RESET}\n`);
  console.log('To setup Gmail SMTP, please provide your Gmail and 16-character App Password:');
  console.log(`\n${BOLD}Command Syntax:${RESET}`);
  console.log(`  node scripts/setup-gmail-smtp.mjs <your-gmail@gmail.com> "<16-char-app-password>" --save\n`);
  console.log(`${BOLD}How to generate Google 16-character App Password:${RESET}`);
  console.log('  1. Open Google Account Security: https://myaccount.google.com/security');
  console.log('  2. Enable "2-Step Verification" (if not already enabled).');
  console.log('  3. In the search bar at top, type "App Passwords".');
  console.log('  4. Set App name: "DocSearch Healthcare" and click Create.');
  console.log('  5. Copy the 16-character password generated by Google.\n');
  process.exit(1);
}

console.log(`\n🔍 ${BOLD}Testing Gmail Configuration:${RESET}`);
console.log(`  • Gmail Address: ${CYAN}${user}${RESET}`);
console.log(`  • App Password : ${CYAN}•••••••••••••••• (${appPassword.length} chars)${RESET}`);

async function run() {
  console.log(`\n⏳ ${CYAN}Connecting to smtp.gmail.com (TLS Port 465/587)...${RESET}`);

  const transporter = nodemailer.createTransport({
    service: 'gmail',
    auth: {
      user: user,
      pass: appPassword
    }
  });

  try {
    // Step 1: Verify Authentication with Gmail Server
    await transporter.verify();
    console.log(`\n${GREEN}✅ SUCCESS: Gmail SMTP Authentication Verified!${RESET}`);
    console.log(`   Connected securely to Google Mail servers with user: ${user}`);

    // Step 2: Send a live test email if requested or default to user
    const recipient = sendTo || user;
    console.log(`\n⏳ Dispatching live test email to: ${CYAN}${recipient}${RESET}...`);

    const info = await transporter.sendMail({
      from: `"DocSearch Healthcare" <${user}>`,
      to: recipient,
      subject: '✅ DocSearch Healthcare: Gmail SMTP Connected Successfully',
      html: `
<!DOCTYPE html>
<html>
<head><meta charset="utf-8"/><title>Gmail SMTP Verified</title></head>
<body style="margin:0;padding:24px;background-color:#0f172a;font-family:sans-serif;color:#f8fafc;">
  <div style="max-width:520px;margin:auto;background-color:#1e293b;border-radius:14px;border:1px solid #334155;padding:28px;">
    <h2 style="color:#38bdf8;margin:0 0 10px;">🎉 DocSearch Gmail SMTP Live!</h2>
    <p style="color:#cbd5e1;font-size:14px;line-height:1.5;">
      Congratulations! Your DocSearch Enterprise API Gateway has successfully connected to Google Mail SMTP and sent this live verification email.
    </p>
    <div style="background-color:#0f172a;border-radius:8px;padding:14px;border:1px solid #334155;font-family:monospace;font-size:12px;margin:18px 0;">
      <div style="color:#64748b;">DISPATCH DETAILS:</div>
      <div style="color:#34d399;margin-top:4px;">STATUS: AUTHENTICATED & DELIVERED</div>
      <div style="color:#94a3b8;margin-top:2px;">SENDER: ${user}</div>
      <div style="color:#94a3b8;margin-top:2px;">TIMESTAMP: ${new Date().toISOString()}</div>
    </div>
    <div style="font-size:11px;color:#64748b;border-top:1px solid #334155;padding-top:12px;text-align:center;">
      DocSearch Healthcare Monorepo • Multi-Tenant Enterprise Health Systems
    </div>
  </div>
</body>
</html>`.trim()
    });

    console.log(`${GREEN}✅ Test Email Dispatched Successfully!${RESET}`);
    console.log(`   Message ID: ${info.messageId}`);

    // Step 3: Save to .env if requested
    if (shouldSave) {
      saveToEnv(user, appPassword);
    } else {
      console.log(`\n💡 ${YELLOW}Tip: To permanently save this to .env, pass the --save flag:${RESET}`);
      console.log(`   node scripts/setup-gmail-smtp.mjs "${user}" "${appPassword}" --save\n`);
    }

  } catch (err) {
    console.log(`\n${RED}❌ ERROR: Failed to Authenticate with Gmail SMTP!${RESET}`);
    console.log(`   Details: ${err.message}\n`);
    console.log(`${BOLD}Troubleshooting Checklist:${RESET}`);
    console.log('   1. Ensure your Google Account has "2-Step Verification" turned ON.');
    console.log('   2. Do NOT use your regular Google account password. You MUST use a 16-character App Password.');
    console.log('   3. Generate it at: https://myaccount.google.com/apppasswords');
    console.log('   4. Ensure there are no typos in your Gmail address.\n');
    process.exit(1);
  }
}

function saveToEnv(email, pass) {
  let content = envContent;
  const fromFormatted = `"DocSearch Healthcare <${email}>"`;
  const kvPairs = {
    GMAIL_USER: email,
    GMAIL_APP_PASSWORD: pass,
    GMAIL_FROM: fromFormatted,
    SMTP_HOST: 'smtp.gmail.com',
    SMTP_PORT: '465',
    SMTP_SECURE: 'true',
    SMTP_USER: email,
    SMTP_PASSWORD: pass,
    SMTP_FROM: fromFormatted
  };

  for (const [key, val] of Object.entries(kvPairs)) {
    const regex = new RegExp(`^${key}=.*$`, 'm');
    if (content.match(regex)) {
      content = content.replace(regex, `${key}=${val}`);
    } else {
      content += `\n${key}=${val}`;
    }
  }

  fs.writeFileSync(ENV_PATH, content.trim() + '\n', 'utf8');
  console.log(`\n${GREEN}💾 SAVED: Successfully updated .env with GMAIL_* and SMTP_* Gmail credentials!${RESET}\n`);
}

run();
